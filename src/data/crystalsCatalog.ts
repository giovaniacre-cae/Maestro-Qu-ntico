export function getCrystalByName(value?: string | null): CrystalCatalogEntry | undefined {
  if (!value) return undefined;
  const trimmed = value.trim().toLowerCase();
  if (!trimmed) return undefined;
  return CRYSTALS_CATALOG.find(
    (c) =>
      c.id === trimmed ||
      c.name.toLowerCase() === trimmed ||
      c.displayLabel.toLowerCase() === trimmed
  );
}
