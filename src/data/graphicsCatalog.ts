export function findRadionicGraphic(name: string): RadionicGraphicEntry | undefined {
  const normalized = name.trim().toLowerCase();
  if (!normalized) return undefined;
  return RADIONIC_GRAPHICS_CATALOG.find(
    (g) =>
      g.id === normalized ||
      g.name.toLowerCase() === normalized
  );
}
